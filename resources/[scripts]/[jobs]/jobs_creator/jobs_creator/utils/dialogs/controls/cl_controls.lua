local function detectPressedControls()
  local pressedControls = {}
  while true do
    Citizen.Wait(0)
    DisableAllControlActions(0)
    for i = 1, #controls do
      local control = controls[i]
      if IsDisabledControlJustReleased(0, control.id) then
        pressedControls[#pressedControls + 1] = control
      end
    end
    if #pressedControls > 0 then
      return pressedControls
    end
  end
end

local function callbackHandler(data, callback)
  SetNuiFocusKeepInput(true)
  local pressedControls = detectPressedControls()
  SetNuiFocusKeepInput(false)
  callback(pressedControls)
end

registerCallback("detectPressedControls", callbackHandler)
